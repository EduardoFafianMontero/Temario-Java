
public class TiposDatosPrimitivos {
    public static void main(String[] args) {

        System.out.println("Tipos de datos primitivos");

        int edad = 20;
        System.out.println("Mi edad es: " + edad);

        double suma = 1.75;
        System.out.println("La suma es: " + suma);

        char clase = 'A';
        System.out.println("La clase que me tocó es: " + clase);

        boolean notaFinal = true;
        System.out.println("¿La nota final está aprobada?: " + notaFinal);

        String nombreAlumno = "Eduardo Fafian Montero";
        System.out.println("El nombre del alumno es: " + nombreAlumno);
    }
}
